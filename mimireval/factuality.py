"""Hallucination / factuality benchmarks: generate with vLLM, score with judges.

Tasks: SimpleQA Verified, TruthfulQA (generation + generative MC1), HHEM summarization faithfulness,
HalluLens PreciseWikiQA, LongWiki and NonExistentRefusal (MixedEntities).
"""
import json

from mimireval.io import GEN_DIR, SCORE_DIR, read_jsonl, write_jsonl
from mimireval.tasks import hhem, simpleqa, truthfulqa_gen, truthfulqa_mc_gen

SIMPLE_TASKS = {"simpleqa_verified": simpleqa, "truthfulqa_gen": truthfulqa_gen,
                "truthfulqa_mc1_gen": truthfulqa_mc_gen, "hhem": hhem}
HALLULENS_TASKS = ("precise_wikiqa", "longwiki", "nonexistent_mixed")
TASKS = (*SIMPLE_TASKS, *HALLULENS_TASKS)


def _rows(task: str) -> tuple[list[dict], dict]:
    if task in SIMPLE_TASKS:
        mod = SIMPLE_TASKS[task]
        return mod.load(), mod.GEN
    from mimireval.tasks import hallulens
    hallulens.bootstrap()
    cfg, loader = hallulens.SETS[task]
    return loader(), dict(max_new_tokens=cfg["max_new_tokens"], temperature=0.0, top_p=1.0)


def prepare(tasks=TASKS):
    """Build shared prompt sets once (HalluLens questions are generated by the judge)."""
    for task in tasks:
        rows, _ = _rows(task)
        print(f"[prepare] {task}: {len(rows)} prompts")


def generate(model: str, tasks=TASKS):
    from mimireval.generate import Generator

    gen = None
    for task in tasks:
        out = GEN_DIR / model / task / "seed0.jsonl"
        if out.exists():
            continue
        rows, hp = _rows(task)
        gen = gen or Generator(model)
        completions = gen.generate([r["prompt"] for r in rows], seed=0, **hp)
        write_jsonl(out, [{**{k: v for k, v in r.items() if isinstance(v, (str, int, float, bool, list))},
                           "completion": c, **hp} for r, c in zip(rows, completions)])
        print(f"[gen] {model}/{task}: {len(rows)} prompts")


def _judge_task(task, rows, generations, judge_model):
    from mimireval.judge import Judge
    mod = SIMPLE_TASKS[task]
    raw = Judge(judge_model)(mod.judge_prompts(rows, generations), desc=task)
    if task == "simpleqa_verified":
        grades = [mod.parse_grade(r) for r in raw]
    else:
        grades = [mod.parse(r) for r in raw]
    return mod.metrics(grades), grades


def score(models: list[str], tasks=TASKS, judge_model: str | None = None):
    from mimireval.judge import PRIMARY_JUDGE

    judge_model = judge_model or PRIMARY_JUDGE
    suffix = "" if judge_model == PRIMARY_JUDGE else "." + judge_model.split("/")[-1]
    for task in tasks:
        for model in models:
            src = GEN_DIR / model / task / "seed0.jsonl"
            out = SCORE_DIR / model / task / f"seed0{suffix}.json"
            if out.exists() or not src.exists():
                continue
            records = read_jsonl(src)
            generations = [r["completion"] for r in records]
            if task == "hhem":
                report, items = hhem.score(records, generations)
            elif task == "truthfulqa_mc1_gen":
                report, items = truthfulqa_mc_gen.metrics(records, generations)
            elif task in SIMPLE_TASKS:
                report, items = _judge_task(task, records, generations, judge_model)
            else:
                from mimireval.tasks import hallulens
                hallulens.bootstrap(judge_model)
                hallulens.write_generations(task, model + suffix, records, generations)
                report, items = hallulens.evaluate(task, model + suffix), []
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(json.dumps({"report": report, "judge": judge_model}, indent=1, default=str))
            if items:
                write_jsonl(out.with_suffix(".items.jsonl"), [{"grade": g} for g in items])
            print(f"[score] {model}/{task}{suffix}: {report}")
